def expiring_cert(d: Path, days: int = 1):
    tls = d / "tls"
    tls.mkdir(exist_ok=True)
    subprocess.run(["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", str(days),
                    "-subj", "/CN=localhost", "-addext", "subjectAltName=DNS:localhost",
                    "-keyout", str(tls / "key.pem"), "-out", str(tls / "cert.pem")],
                   check=True, capture_output=True)
    return (tls / "cert.pem").read_bytes(), (tls / "key.pem").read_bytes()


def test_renew_tls_is_deferred_during_an_upgrade_or_while_locked(host, tmp_path):
    old = release_install(host, tmp_path)
    expiring_cert(old, days=20)
    fd = lock_folder(old)
    try:
        r = run_installer(old, "--renew-tls", host=host)
    finally:
        os.close(fd)
    assert r.returncode == 0, r.stderr
    # On stderr, so cron reports it.
    assert "==> TLS renewal deferred: another installer run holds the lock " \
        "(bash install-release.sh --status)." in r.stderr
    new = unpacked_release(tmp_path)
    # Stopped in the switch, with the stack down: the renewal waits.
    assert fail_upgrade_at(host, old, new, r"^compose config --environment$", [1, 1]).returncode in (1, 4)
    assert journal(old)["state"] == "failed"
    cert = (old / "tls" / "cert.pem").read_bytes()
