def test_upgrade_dir_touches_dir_only_after_the_pull(host, tmp_path):
    old = release_install(host, tmp_path)
    shutil.copy(OLD_INSTALLER, old / "install-release.sh")
    new = unpacked_release(tmp_path)
    host.update(watch_dir=str(old))
    r = run_installer(new, "--upgrade", str(old), host=host)
    assert r.returncode == 0, r.stdout + r.stderr
    calls = host.calls()
    argvs = [" ".join(c["argv"]) for c in calls]
    initial = calls[0]["watch"]
    pull_b = index_of(argvs, rf"^pull --quiet {re.escape(NEW_BRIDGE)}$")
    pull_g = index_of(argvs, rf"^pull --quiet {re.escape(NEW_GATEWAY)}$")
    # DIR is as it was while both images are pulled, and nothing started or
    # stopped before.
    assert calls[pull_b]["watch"] == calls[pull_g]["watch"] == initial
    assert not any(re.search(r"^compose (up|stop|start)|^stop ", a) for a in argvs[:pull_g])
    assert calls[-1]["watch"] != initial
    # The new installer and release files are in DIR now; the old
    # installer is kept beside it.
    assert (old / "install-release.sh").read_bytes() == INSTALL_RELEASE.read_bytes()
    backups = list(old.glob("install-release.sh.bak.*~"))
    assert len(backups) == 1 and backups[0].read_bytes() == OLD_INSTALLER.read_bytes()
    for name in ("LICENSE", "NOTICE", "THIRD-PARTY-NOTICES.txt", "README-INSTALL.txt"):
        assert (old / name).read_bytes() == (new / name).read_bytes(), name
    assert os.stat(old / "install-release.sh").st_mode & 0o777 == 0o755
    assert journal(old)["installer_backups"] == [backups[0].name]
    assert_upgraded(host, old)


