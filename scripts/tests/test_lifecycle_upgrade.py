def engine_requests(host) -> list[dict]:
    """The requests (JSON) the engine got on stdin, in order."""
    out = []
    for raw in host.engine_inputs():
        rest = raw
        for _ in range(2):
            n, _, rest = rest.partition(b"\n")
            body, rest = rest[:int(n)], rest[int(n):]
        out.append(json.loads(body))
    return out


