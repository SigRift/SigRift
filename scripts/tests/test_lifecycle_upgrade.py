def test_migration_lines_extend_the_bridge_deadline(tmp_path):
    results = {}
    for name, logs in (("migrating", list(range(1, 16))), ("silent", [0])):
        sub = tmp_path / name
        sub.mkdir()
        host = FakeDockerHost(sub)
        host.update(registry={NEW_BRIDGE: {"newest_migration": 57}, NEW_GATEWAY: {}},
                    health_seq={"bridge": ["starting"] * 14}, migration_logs=logs)
        release_install(host, sub)
        new = unpacked_release(sub)
        results[name] = run_installer(new, host=host, env={"FAKE_CLOCK_STEP": "60"})
    # 14 polls 60 s apart: past the 10-minute deadline, but every poll saw
    # a new "Migration N applied" line.
    ok = results["migrating"]
    assert ok.returncode == 0, ok.stdout + ok.stderr
    assert "bridge: 3 migrations applied so far; waiting while they run" in ok.stdout
    silent = results["silent"]
    assert silent.returncode == 4, silent.stdout + silent.stderr
    assert "The bridge did not become healthy within" in silent.stdout + silent.stderr


