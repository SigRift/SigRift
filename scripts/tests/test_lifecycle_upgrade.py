    assert held and any("--entrypoint" in c["argv"] for c in held)
    assert all(not c["compose_file_head"].startswith(STUB_HEAD) for c in calls[up_bridge:])
    assert not (old / ".sigrift" / "held").exists()
    assert sorted(journal(old)["held"]) == ["docker-compose.override.yml", "docker-compose.yml"]


