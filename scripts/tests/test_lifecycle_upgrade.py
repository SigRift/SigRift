    assert entry["via_helper"] is True
    assert (snap / "files" / "tls" / "key.pem").read_bytes() == data
    reads = [c["argv"] for c in host.calls() if c["argv"][:1] == ["run"]
             and c["argv"][-2:] == ["cat", "/tls/key.pem"]]
    assert reads and all(a[a.index("--log-driver") + 1] == "none" for a in reads)
    assert any(m.endswith(":/tls:ro") for a in reads for m in a)


