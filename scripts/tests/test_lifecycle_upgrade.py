# ── the files-only restore point ────────────────────────────────────────


def test_files_only_snapshot_is_taken_before_any_file_change(host, tmp_path):
    old = release_install(host, tmp_path)
    original = {rel: (old / rel).read_bytes() for rel in (".env", "docker-compose.yml", "VERSION")}
    new = unpacked_release(tmp_path)
    r = run_installer(new, host=host)
    assert r.returncode == 0, r.stdout + r.stderr
    [snap] = [s for s in snapshots(old) if s.name.endswith("-files")]
    manifest_bytes = (snap / "manifest.json").read_bytes()
    manifest = json.loads(manifest_bytes)
    assert manifest["kind"] == "files" and manifest["reason"] == "upgrade"
    assert (manifest["from_version"], manifest["to_version"]) == ("v0.1.0", "v0.2.0")
    assert snap.name == manifest["id"] and snap.name.endswith("-v0.1.0-files")
    files = {f["path"]: f for f in manifest["files"]}
    for rel, data in original.items():
        # The files as they were before the run changed them.
        assert files[rel]["sha256"] == hashlib.sha256(data).hexdigest(), rel
        assert (snap / "files" / rel).read_bytes() == data
    assert {"tls/cert.pem", "tls/key.pem", "LICENSE"} <= set(manifest["missing"])
    # COMPLETE is written last and holds the manifest's digest.
    assert (snap / "COMPLETE").read_text().strip() == hashlib.sha256(manifest_bytes).hexdigest()
    for p in [old / ".sigrift", old / ".sigrift" / "snapshots", snap, snap / "files"]:
        assert p.stat().st_mode & 0o777 == 0o700, p
    for p in snap.rglob("*"):
        if p.is_file():
            assert p.stat().st_mode & 0o777 == 0o600, p
    assert journal(old)["snapshot"] == snap.name


def test_unreadable_tls_key_is_snapshotted_through_the_helper(host, tmp_path):
    old = release_install(host, tmp_path)
    assert run_installer(old, host=host).returncode == 0  # a re-run makes tls/
    key = old / "tls" / "key.pem"
