"""The guarded upgrade of a release install (lifecycle block, PART B).

The installers run for real against FakeDockerHost (lifecycle_fakes.py).
What they must show: the new images are pulled before any file changes; a
files-only restore point is taken before the first change; the stack is
stopped and held by a placeholder compose file while the files change;
the bridge starts first and may take as long as its migrations need; the
steps are journaled, so an interrupted upgrade can be resumed or (before
the new bridge started) aborted; records are written only after a
healthy run; and no secret reaches docker's argv or a daemon log.
"""

