    assert r.returncode in (1, 4), r.stdout + r.stderr
    j = journal(old)
    assert j["state"] in ("failed", "verify_failed") and j["next"] == step, j
    # The detached run's output (both streams) reaches the terminal through
    # the log it follows.
    out = r.stdout + r.stderr
    assert "The upgrade stopped at step" in out or "a check failed" in out, out
    r = run_installer(old, "--resume", host=host)
    assert r.returncode == 0, r.stdout + r.stderr
    assert f"(step {step})" in r.stdout
    assert_upgraded(host, old)


