def journal(d: Path) -> dict:
    return json.loads((d / ".sigrift" / "journal.json").read_text())


def env_of(d: Path) -> dict:
    out = {}
    for line in (d / ".env").read_text().splitlines():
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            out[k] = v
    return out


def snapshots(d: Path) -> list[Path]:
    root = d / ".sigrift" / "snapshots"
    return sorted(root.iterdir()) if root.exists() else []


def index_of(argvs: list[str], pattern: str, start: int = 0) -> int:
    for i, a in enumerate(argvs[start:], start):
        if re.search(pattern, a):
            return i
    raise AssertionError(f"no docker call matches {pattern!r}:\n" + "\n".join(argvs))


def file_state(d: Path) -> dict:
    """Content (or absence) of every file a files-only restore point holds."""
    out = {}
    for rel in SNAPSHOT_FILES:
        p = d / rel
        out[rel] = p.read_bytes() if p.is_file() and os.access(p, os.R_OK) else (
            "<unreadable>" if p.exists() else None)
    return out


def assert_upgraded(host: FakeDockerHost, d: Path, project="sigrift-v010"):
    """The end state of an uninterrupted upgrade of D to v0.2.0."""
    assert (d / "VERSION").read_text() == "v0.2.0\n"
    compose = (d / "docker-compose.yml").read_text()
    assert compose.startswith("# Generated by install-release.sh @ ")
    assert f"image: {NEW_BRIDGE}" in compose and f"image: {NEW_GATEWAY}" in compose
    env = env_of(d)
    assert env["COMPOSE_PROJECT_NAME"] == project and env["BRIDGE_KEYSTORE_KEY"]
    assert not (d / ".sigrift" / "held").exists()
    j = journal(d)
    assert j["state"] == "done" and j["next"] == "" and j["done"] == j["steps"], j
    state = host.load()
    running = {c["service"]: c for c in state["containers"]
               if c["project"] == project and c["state"] == "running"}
    assert running["bridge"]["image"] == NEW_BRIDGE
    assert running["gateway"]["image"] == NEW_GATEWAY
    record = json.loads((d / ".sigrift" / "install.json").read_text())
    assert record["version"] == "v0.2.0" and record["history"][-1]["result"] == "ok"
    assert state["records"][f"{project}_bridge_data"]["last_version"] == "v0.2.0"
    assert state["data"][f"{project}_bridge_data"]["schema"] == 57


def lock_folder(d: Path, owner: dict | None = None):
    """Hold the install folder's lock as another run would; -> the fd."""
    fd = os.open(d, os.O_RDONLY)
    fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    if owner is not None:
        (d / ".sigrift").mkdir(mode=0o700, exist_ok=True)
        (d / ".sigrift" / "lock-owner.json").write_text(json.dumps(owner))
    return fd


