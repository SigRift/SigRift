def test_the_tool_is_compiled_once_into_a_private_cache(tmp_path):
    lib = tmp_path / "tool.sh"
    lib.write_text(shared_block(INSTALL_RELEASE, "lifecycle-tool"))
    cache = tmp_path / f"sigrift-lc-{os.geteuid()}"
    script = f'source "{lib}"; echo "pyc=$LC_TOOL_PYC"; lc_tool version-cmp v0.2.0 v0.1.0'
    env = {"PATH": os.environ["PATH"], "TMPDIR": str(tmp_path)}

    def run():
        r = subprocess.run([BASH, "-c", script], capture_output=True, text=True, env=env)
        assert r.returncode == 0, r.stderr
        return r.stdout.splitlines()

    pyc, cmp = run()
    assert cmp == "1" and pyc.startswith(f"pyc={cache}/lc_tool-") and pyc.endswith(".pyc")
    assert cache.stat().st_mode & 0o777 == 0o700
    assert not Path(pyc[4:]).stat().st_mode & 0o022
    # The same source gives the same file; another folder mode means no
    # cache, and the tool runs from its source.
    assert run()[0] == pyc and len(list(cache.iterdir())) == 1
    cache.chmod(0o777)
    try:
        assert run() == ["pyc=", "1"]
    finally:
        cache.chmod(0o700)
