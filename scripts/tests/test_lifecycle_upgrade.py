def test_critical_section_survives_a_lost_terminal(host, tmp_path):
    old = release_install(host, tmp_path)
    new = unpacked_release(tmp_path)
    host.update(up_sleep=3)
    p = subprocess.Popen([BASH, str(new / "install-release.sh")], cwd=new, env=host.env(),
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
                         start_new_session=True)
    seen = b""
    deadline = time.time() + 120
    while b"stack stopped and held" not in seen and time.time() < deadline:
        line = p.stdout.readline()
        if not line:
            break
        seen += line
    assert b"stack stopped and held" in seen, seen.decode()
    # The terminal goes away: the run that started the upgrade dies and its
    # output pipe is gone.
    os.killpg(p.pid, signal.SIGKILL)
    p.stdout.close()
    p.wait()
    rc = old / (journal(old)["log"][:-len(".log")] + ".rc")
    deadline = time.time() + 120
    while time.time() < deadline and not rc.exists():
        time.sleep(0.2)
    assert rc.read_text().strip() == "0"
    assert journal(old)["state"] == "done", journal(old)
    log = (old / journal(old)["log"]).read_text()
    assert "SigRift v0.2.0 is up in" in log
    assert_upgraded(host, old)


KILLS = {
    "stop": (r"^compose stop$", 1),
    # 1b: the database check on the stopped data (the quiesce engine run).
    "prechecks": (r"--name sigrift-lc-\S+-quiesce-", 1),
    "switch": (r"^compose config --environment$", [1, 1]),
    "start-bridge": (r"--remove-orphans bridge$", 1),
    "start-rest": (r"--remove-orphans( --force-recreate gateway)?$", 1),
    # The checks read the data with the new bridge's image.
    "verify": (re.escape("sha256:" + hashlib.sha256(NEW_BRIDGE.encode()).hexdigest()), 1),
}


