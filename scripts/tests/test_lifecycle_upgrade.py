    assert run_installer(old, host=host).returncode == 0
    (old / "tls" / "key.pem").chmod(0)
    new = unpacked_release(tmp_path)
    assert run_installer(new, host=host).returncode == 0
    runs = [c["argv"] for c in host.calls() if c["argv"][:1] == ["run"]]
    carrying = [a for a in runs if "-i" in a or "cat" in a or "--entrypoint" in a]
    assert len(carrying) >= 4
    for a in carrying:
        assert "--log-driver" in a and a[a.index("--log-driver") + 1] == "none", a
    # And confined: the engine as the bridge's uid with no capabilities,
    # the TLS helper with only the one it needs; none may gain privileges.
    engine = [" ".join(a) for a in runs if "--entrypoint" in a]
    tls = [" ".join(a) for a in runs if "--label com.sigrift.lifecycle=tls" in " ".join(a)]
    assert engine and tls
    for joined in engine:
        assert "--user 1500:1500" in joined and "--cap-drop ALL" in joined, joined
        assert "--label com.sigrift.lifecycle=engine" in joined or \
            "--label com.sigrift.lifecycle=state-engine" in joined, joined
    for joined in tls:
        assert "--cap-drop ALL --cap-add DAC_OVERRIDE" in joined, joined
    assert all("--security-opt no-new-privileges" in j for j in engine + tls)
    # Statically: every `docker run` in the lifecycle blocks says so too.
    for name in LIFECYCLE_BLOCKS:
        block = shared_block(INSTALL_RELEASE, name)
        # A command (`docker run --rm ...`), not a message ("docker run exited").
        bash_runs = re.findall(r"docker run -[^\n]*(?:\\\n[^\n]*)*", block)
        py_runs = re.findall(r'(?:docker\(|args = \[)"run",[^\]\)]*', block)
        for run in bash_runs + py_runs:
            assert "--log-driver" in run and "none" in run, (name, run)
    tool = shared_block(INSTALL_RELEASE, "lifecycle-tool")
    # The tool's runs all go through helper_run_args, which says so, labels
    # them and drops the right to gain privileges.
    assert re.search(r'args = \["run", "--rm", "--log-driver", "none", "--network", "none",\n'
                     r'\s+"--label", "%s=%s" % \(LIFECYCLE_LABEL, kind\),\n'
                     r'\s+"--security-opt", "no-new-privileges"\]', tool)
    assert not re.search(r'docker\("run"', tool)
    assert len(re.findall(r"helper_run_args\(", tool)) >= 5


