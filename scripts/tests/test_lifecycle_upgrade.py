def test_pruning_keeps_ten_and_the_journal_reference(tmp_path):
    tool = load_lifecycle_tool()
    root = tmp_path / ".sigrift" / "snapshots"
    root.mkdir(parents=True)
    ids = []
    for i in range(13):
        sid = f"2026112{i // 10}T10{i % 10}000Z-v0.1.0-files"
        d = root / sid
        (d / "files").mkdir(parents=True)
        manifest = json.dumps({"format": 1, "kind": "files", "id": sid,
                               "created_at": f"2026-11-2{i // 10}T10:{i:02d}:00Z"}).encode()
        (d / "manifest.json").write_bytes(manifest)
        (d / "COMPLETE").write_text(hashlib.sha256(manifest).hexdigest() + "\n")
        ids.append(sid)
    incomplete = root / "20261101T000000Z-v0.0.9-files"
    incomplete.mkdir()
    (tmp_path / ".sigrift" / "journal.json").write_text(json.dumps({"snapshot": ids[0]}))
    tool.os.chdir(tmp_path)
    removed = tool.prune_snapshots(str(tmp_path), 10, {ids[0]})
    assert sorted(removed) == sorted(ids[1:3])
    left = sorted(p.name for p in root.iterdir())
    assert left == sorted([ids[0]] + ids[3:] + [incomplete.name])


